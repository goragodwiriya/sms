-- install/database.sql — ตารางของ "โปรเจ็คนี้" ที่ไม่มีโมดูลไหนเป็นเจ้าของ
--
-- กติกาการแบ่งไฟล์ (ยึดตามนี้ทุกโปรเจ็ค)
--
--   install/core.sql                     ตารางแกนของ Gcms — เหมือนกันทุกโปรเจ็ค
--   modules/<m>/install/database.sql     ตารางที่โมดูล <m> เป็นเจ้าของ + ข้อมูลตั้งต้นของมัน
--   install/database.sql  (ไฟล์นี้)      เฉพาะตารางที่ไม่มีโมดูลไหนเป็นเจ้าของ
--
-- และฝั่งตัวปรับรุ่นแบ่งคู่กันตรง ๆ
--
--   install/upgrade_core.php             ตารางแกน + เรียก upgrade.php ของทุกโมดูลให้เอง
--   modules/<m>/install/upgrade.php      ตารางของโมดูล <m>
--   install/upgrade2.php                 เฉพาะของโปรเจ็ค + ลำดับการทำงานทั้งหมด
--
-- ⚠️ ห้ามประกาศตารางเดียวกันสองที่ — schemaFiles() อ่านทุกไฟล์ ติดตั้งใหม่จะล้ม
-- ด้วย "Table already exists" และนิยามสองชุดจะค่อย ๆ ต่างกันจนไซต์ที่อัปเกรด
-- คนละเส้นทางได้สคีมาไม่เหมือนกัน
--
-- ⚠️ schemaFiles() รันไฟล์นี้ **ก่อน** ไฟล์ของโมดูล — INSERT ที่ชี้ไปยังตาราง
-- ของโมดูลต้องอยู่ในไฟล์ของโมดูล ไม่ใช่ที่นี่ (ไม่งั้นวิ่งไปหาตารางที่ยังไม่ถูกสร้าง)
--
-- ตอนนี้ไม่มีตารางที่ไม่มีเจ้าของเหลืออยู่ และไม่มีข้อมูลตั้งต้นของโปรเจ็คด้วย
-- หมวดหมู่ของ SMS (ตำแหน่ง แผนก ชั้น ห้อง ภาคเรียน) เป็นของโมดูล personnel
-- กับ school จึงอยู่ใน modules/<m>/install/database.sql ของโมดูลนั้น
-- (แผนก = กลุ่มสาระการเรียนรู้ ใช้ร่วมกันทั้งบุคลากรและนักเรียน)
