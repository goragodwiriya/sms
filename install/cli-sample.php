<?php
/**
 * install/cli-sample.php — ใส่ข้อมูลตัวอย่างของระบบบริหารสถานศึกษา (SMS) ให้ครบทุกส่วนพอสำหรับทดสอบ
 *
 * สร้าง
 *   บุคลากร    ผู้อำนวยการ รองฯ 2 คน ครูกลุ่มสาระละ 3 คน (หัวหน้ากลุ่มสาระ งานทะเบียน ครูประจำชั้นทุกห้อง)
 *              เจ้าหน้าที่ธุรการ และบุคลากรในอดีต · สิทธิ์ตามหน้าที่
 *   นักเรียน   ม.1–ม.6 ชั้นละ 2 ห้อง ห้องละ 15 คน พร้อมเลขที่ ผู้ปกครอง ที่อยู่
 *   รายวิชา    ภาคเรียนปัจจุบันและปีการศึกษาก่อนหน้า (พื้นฐาน เพิ่มเติม กิจกรรม) พร้อมผู้สอน
 *   ผลการเรียน ลงทะเบียนตามชั้น/ห้องของปีนั้น ภาคเรียนที่จบแล้วมีผลครบ (มี ร. มส. มผ. ปนบ้าง)
 *              ภาคเรียนปัจจุบันมีคะแนนกลางภาคครบ ปลายภาคบางวิชา เกรดคำนวณด้วยเกณฑ์จริง (School\Score)
 *   หนังสือเวียน ตลอดภาคเรียนปัจจุบัน มีไฟล์จริงใน datas/edocument/ เลขที่ออกด้วย Index\Number
 *              พร้อมประวัติการดาวน์โหลด
 *   ประวัติการใช้งาน (เข้าระบบ บันทึกรายวิชา ลงทะเบียน ส่งหนังสือ)
 *   หมวดหมู่ที่ยังขาด (ห้องเรียน ม.4–ม.6 ตำแหน่งครูผู้ช่วย ครูอัตราจ้าง เจ้าหน้าที่ธุรการ)
 *
 * บัญชีตัวอย่างเข้าระบบได้ตามกติกาของระบบ: ชื่อผู้ใช้ = เลขประชาชน, รหัสผ่าน = วันเกิด พ.ศ. ปปปปดดวว
 * (ท้ายการรันพิมพ์บัญชีสำหรับทดสอบแต่ละบทบาทให้)
 *
 * เลขประชาชนตัวอย่างขึ้นต้นด้วย 99 เสมอ (เลขจริงหลักแรกเป็น 1–8 จึงไม่ชนกับคนจริง) ใช้เป็นเครื่องหมาย
 * ของบุคลากร/นักเรียนตัวอย่าง และทุกอย่างที่ผูกกับพวกเขา (รายวิชา ผลการเรียน ประวัติ) หนังสือเวียน
 * ตัวอย่างมี "[ตัวอย่าง]" ในรายละเอียด รันซ้ำได้: ของตัวอย่างเดิมถูกลบก่อนใส่ใหม่
 * หมวดหมู่ที่เพิ่มให้คงอยู่หลังลบ (เป็นค่าตั้งของโรงเรียน ไม่ใช่ข้อมูล)
 *
 * ⚠️ ไม่ส่งอีเมล/แจ้งเตือนใด ๆ (เขียนฐานตรง) · ห้ามใช้กับฐานที่โรงเรียนใช้งานจริง
 * รหัสผ่านเข้ารหัสด้วย bcrypt ของระบบ ~200 บัญชีใช้เวลาราวหนึ่งนาที
 *
 * ใช้:  php install/cli-sample.php [--db=<dbname>] [--settings] [--remove]
 *
 *   --db=<dbname>  ใส่ลงฐานอื่นแทนฐานใน settings/database.php
 *   --settings     เติมข้อมูลโรงเรียน (ชื่อ ที่อยู่ โทรศัพท์) ใน settings/config.php เฉพาะช่องที่ยังว่าง
 *   --remove       ลบเฉพาะแถวตัวอย่าง ไม่ใส่ใหม่
 */
if (PHP_SAPI !== 'cli') {
    exit('CLI only');
}
$root = dirname(__DIR__);
chdir($root);
$options = ['db' => '', 'settings' => false, 'remove' => false];
foreach (array_slice($argv, 1) as $arg) {
    if (preg_match('/^--([a-z]+)(?:=(.*))?$/', $arg, $m) && array_key_exists($m[1], $options)) {
        $options[$m[1]] = isset($m[2]) ? $m[2] : true;
    } else {
        fwrite(STDERR, "ไม่รู้จักตัวเลือก $arg\n");
        exit(1);
    }
}
$database = include $root.'/settings/database.php';
if ($options['db'] !== '') {
    $database['mysql']['dbname'] = $options['db'];
}
$work = sys_get_temp_dir().'/nowjs-sample-'.md5($root.$database['mysql']['dbname']);
@mkdir($work.'/settings', 0700, true);
file_put_contents($work.'/settings/database.php', "<?php\nreturn ".var_export($database, true).";\n");
define('APP_PATH', $work.'/');
$_SERVER['HTTP_HOST'] = 'localhost';
$_SERVER['REQUEST_URI'] = '/api';
$_SERVER['SCRIPT_NAME'] = '/api.php';
$_SERVER['REQUEST_METHOD'] = 'GET';
$_SERVER['REMOTE_ADDR'] = '127.0.0.1';
session_save_path(sys_get_temp_dir());
@session_start();
include $root.'/load.php';
Kotchasan::createWebApplication('Gcms\Config');


include __DIR__.'/sample.php';
